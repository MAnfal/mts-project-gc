// The context the browser sends with a follow-up question, built from a real recorded example run (public/examples,
// generated by scripts/build-examples.sh) the way the Report screen builds its view: reduceEvents, then applyConfirmed.
const example = (suffix: string) => {
  const dir = path.resolve(import.meta.dirname, "../../../public/examples");
  const file = fs.readdirSync(dir).find((f) => f.endsWith(`${suffix}.json`));
  if (!file) throw new Error(`no example ending ${suffix}`);
  return JSON.parse(fs.readFileSync(path.join(dir, file), "utf8")) as ExampleRun;
};
const viewOf = (ex: ExampleRun, confirmed: string[] = []) => applyConfirmed(reduceEvents(ex.events), confirmed, ex.profile.generalCounsel);

/** Every object key anywhere in `value`. */
function keysOf(value: unknown, out = new Set<string>()): Set<string> {
  if (Array.isArray(value)) value.forEach((v) => keysOf(v, out));
  else if (value && typeof value === "object")
    for (const [k, v] of Object.entries(value)) {
      out.add(k);
      keysOf(v, out);
    }
  return out;
}

// The whitelist, spelled out: a builder that spreads an item, a deadline or the profile adds keys outside it
// (deadlines, quote, verifyNote, sourceTag, citationVerified, datesShown, id, use, markdown, steps…).
const ALLOWED = new Set([
  // run
  "company", "windowStart", "windowEnd", "asOf", "scanned", "notReviewedCount", "items", "checkedByYou", "heldBack", "screenedOut", "profile",
  // item
  "source", "document_number", "title", "type", "agencies", "tier", "tierReason", "deadline", "dates", "owner", "areas", "reason", "action", "citation", "url",
  // date, owner
  "date", "kind", "name", "email",
  // profile
  "summary", "businessLines", "applies", "doesNotApply", "description", "generalCounsel",
]);

describe("buildFollowUpContext on a recorded example run", () => {
  const ex = example("t6m4"); // Ledgerly, Nov 2–6: three items, twenty screened out
  const view = viewOf(ex);
  const ctx = buildFollowUpContext(view, ex.profile);

  it("carries only whitelisted fields, and nothing that names a score, a model or a prompt", () => {
    const extra = [...keysOf(ctx)].filter((k) => !ALLOWED.has(k));
    expect(extra).toEqual([]);
    const text = JSON.stringify(ctx);
    expect(text).not.toMatch(/probab|typesafe|claude-|anthropic\/|openai\/|"model"|"prompt"|"system"/i);
  });

  it("lists the items in report order, numbered like the report's source chips, with what the GC sees on each", () => {
    const sorted = sortItems(view.items);
    expect(ctx.items.map((i) => [i.source, i.document_number])).toEqual(sorted.map((i, n) => [n + 1, i.document_number]));
    const iran = ctx.items.find((i) => i.document_number === "2026-22685")!;
    expect(iran).toEqual({
      source: expect.any(Number),
      document_number: "2026-22685",
      title: "Continuation of the National Emergency With Respect to Iran",
      type: "Presidential Document",
      agencies: ["Executive Office of the President"],
      tier: "Medium",
      tierReason: "notice with effective deadline in 8 days",
      deadline: { date: "2026-11-14", kind: "effective" },
      dates: [{ date: "2026-11-14", kind: "effective" }],
      owner: { name: "Marcus Lee (Sanctions)", email: "sanctions@ledgerly.example" },
      areas: ["sanctions"],
      reason: expect.stringContaining("Iran national emergency"),
      action: expect.stringContaining("sanctions screening program"),
      citation: "91 FR 69947",
      url: expect.stringContaining("federalregister.gov"),
    });
  });

  it("carries the run's window and counts, the screened-out list with reasons, and the profile it ran with", () => {
    const done = ex.events.find((e) => e.type === "run.done")!;
    expect(ctx).toMatchObject({ company: "Ledgerly Inc.", windowStart: "2026-11-02", windowEnd: "2026-11-06", asOf: "2026-11-06" });
    expect(done.type === "run.done" && [ctx.scanned, ctx.notReviewedCount]).toEqual(done.type === "run.done" && [done.scanned, done.notReviewedCount]);
    expect(ctx.screenedOut).toEqual(view.screenedOut.map(({ document_number, title, reason }) => ({ document_number, title, reason })));
    expect(ctx.screenedOut.length).toBeGreaterThan(0);
    expect(ctx.profile.name).toBe("Ledgerly Inc.");
    expect(ctx.profile.areas.map((a) => a.name)).toEqual(Object.keys(ex.profile.areas));
    expect(ctx.profile.generalCounsel).toEqual(ex.profile.generalCounsel);
  });

  it("a run with nothing to report is still a valid context: 0 items, its closest calls kept", () => {
    const empty = example("l14a");
    const c = buildFollowUpContext(viewOf(empty), empty.profile);
    expect(c.items).toEqual([]);
    expect(c.checkedByYou).toEqual([]);
    expect(c.screenedOut.length).toBeGreaterThan(0);
  });
});

describe("buildFollowUpContext copies a whitelist, not the view", () => {
  const ex = example("t6m4");
  const base = viewOf(ex);

  it("drops an internal field added to an item, a deadline, the view or the profile", () => {
    const item = { ...base.items[0], jevProbability: 0.93, debug: { model: "typesafe-ai/jev" }, deadline: { ...base.items[0].deadline!, quote: "verbatim" } } as ActionItem;
    const view = { ...base, items: [item, ...base.items.slice(1)], debug: { model: "typesafe-ai/jev" } } as RunViewState;
    const profile = { ...ex.profile, prompt: "You are a triage model", areas: { ops: { description: "x", owner: ex.profile.generalCounsel, model: "anthropic/x" } } };
    const ctx = buildFollowUpContext(view, profile as typeof ex.profile);
    const text = JSON.stringify(ctx);
    expect(text).not.toMatch(/jevProbability|typesafe|debug|verbatim|You are a triage model|anthropic/);
    expect([...keysOf(ctx)].filter((k) => !ALLOWED.has(k))).toEqual([]);
  });

  it("includes held-back items the GC confirmed, marked untiered, and keeps the rest held back", () => {
    const dropped = [
      { document_number: "2026-1", title: "Checked by the GC", reason: "Deadline didn't match" },
      { document_number: "2026-2", title: "Still held back", reason: "Citation didn't match" },
    ];
    const view = applyConfirmed({ ...reduceEvents(ex.events), dropped }, ["2026-1"], ex.profile.generalCounsel);
    const ctx = buildFollowUpContext(view, ex.profile);
    expect(ctx.checkedByYou).toEqual([
      {
        document_number: "2026-1",
        title: "Checked by the GC",
        reason: "Deadline didn't match",
        tier: "Not tiered",
        owner: ex.profile.generalCounsel,
        url: "https://www.federalregister.gov/d/2026-1",
      },
    ]);
    expect(ctx.heldBack).toEqual([{ document_number: "2026-2", title: "Still held back", reason: "Citation didn't match" }]);
  });
});

describe("followUpChatId: the chat shows only under a finished report", () => {
  it("keys a finished live run and a finished example apart, by kind and id", () => {
    expect(followUpChatId("live", "r1", "done")).toBe("live:r1");
    expect(followUpChatId("example", "2026-x", "done")).toBe("example:2026-x");
  });

  it("is null while the run is running, and after it failed or was interrupted", () => {
    for (const status of ["running", "failed", "interrupted"]) expect(followUpChatId("live", "r1", status)).toBeNull();
    expect(followUpChatId("example", "e1", "failed")).toBeNull();
  });
});

// ── askFollowUp: one question, streamed as NDJSON lines from /api/followup ──

const enc = new TextEncoder();
/** A response body that delivers `text` in `size`-byte pieces (lines and multi-byte characters get cut). */
function body(text: string, size = 7): ReadableStream<Uint8Array> {
  const bytes = enc.encode(text);
  let i = 0;
  return new ReadableStream({
    pull(c) {
      if (i >= bytes.length) return c.close();
      c.enqueue(bytes.slice(i, i + size));
      i += size;
    },
  });
}
const lines = (...ls: object[]) => ls.map((l) => JSON.stringify(l) + "\n").join("");
const ndjson = (text: string) => new Response(body(text), { status: 200, headers: { "content-type": "application/x-ndjson; charset=utf-8" } });
const plain = (text: string, status: number) => new Response(text, { status, headers: { "content-type": "text/plain; charset=utf-8" } });

const ex = example("t6m4");
const context: FollowUpContext = buildFollowUpContext(viewOf(ex), ex.profile);
const earlier: ChatTurn[] = [
  { role: "user", content: "Who owns the Iran item?" },
  { role: "assistant", content: "Marcus Lee [1]." },
];

async function ask(response: () => Promise<Response>, turns: ChatTurn[] = earlier) {
  const store = await openRunStore(undefined);
  const sent: { url: string; body: unknown }[] = [];
  const texts: string[] = [];
  const f = (async (url: string, init: RequestInit) => {
    sent.push({ url, body: JSON.parse(String(init.body)) });
    return response();
  }) as unknown as typeof fetch;
  const result = await askFollowUp(
    { chatId: "live:r1", context, turns, question: "  Summarize for the CEO in 3 lines  " },
    { fetch: f, store, onText: (t) => texts.push(t), now: () => "2026-11-23T10:00:00.000Z" },
  );
  return { result, sent, texts, saved: await store.getChat("live:r1") };
}

describe("askFollowUp", () => {
  it("posts the context and the conversation with the trimmed question last, streams the answer, and saves the pair", async () => {
    const r = await ask(async () => ndjson(lines({ type: "text", text: "Three items — “all” " }, { type: "text", text: "sanctions." }, { type: "done" })));
    expect(r.sent).toEqual([{ url: "/api/followup", body: { context, messages: [...earlier, { role: "user", content: "Summarize for the CEO in 3 lines" }] } }]);
    expect(r.texts.join("")).toBe("Three items — “all” sanctions.");
    const turns = [...earlier, { role: "user", content: "Summarize for the CEO in 3 lines" }, { role: "assistant", content: "Three items — “all” sanctions." }];
    expect(r.result).toEqual({ ok: true, turns });
    expect(r.saved).toEqual({ id: "live:r1", savedAt: "2026-11-23T10:00:00.000Z", turns });
  });

  it("a stream that ends with the failure line: not ok, the route's sentence, nothing saved", async () => {
    const r = await ask(async () => ndjson(lines({ type: "text", text: "Three it" }, { type: "failed", message: FOLLOWUP_FAILED })));
    expect(r.texts).toEqual(["Three it"]);
    expect(r.result).toEqual({ ok: false, message: FOLLOWUP_FAILED });
    expect(r.saved).toBeNull();
  });

  it("a stream that stops without a done line (dropped connection, function timeout) counts as failed, not finished", async () => {
    const r = await ask(async () => ndjson(lines({ type: "text", text: "Three items" })));
    expect(r.result).toEqual({ ok: false, message: FOLLOWUP_FAILED });
    expect(r.saved).toBeNull();
  });

  it("a finished stream with no text is not an answer", async () => {
    const r = await ask(async () => ndjson(lines({ type: "done" })));
    expect(r.result).toEqual({ ok: false, message: FOLLOWUP_FAILED });
    expect(r.saved).toBeNull();
  });

  it("a refusal shows the route's plain sentence", async () => {
    const r = await ask(async () => plain("This conversation has reached its length limit. Clear it to ask more.", 400));
    expect(r.result).toEqual({ ok: false, message: "This conversation has reached its length limit. Clear it to ask more." });
    expect(r.saved).toBeNull();
  });

  it("an answer that isn't the route's own (an HTML error page, a platform timeout) is never shown", async () => {
    const r = await ask(async () => new Response("<html>504 Gateway Timeout</html>", { status: 504, headers: { "content-type": "text/html" } }));
    expect(r.result).toEqual({ ok: false, message: FOLLOWUP_UNAVAILABLE });
  });

  it("a request that never reaches the server (offline) gets the fixed sentence", async () => {
    const r = await ask(async () => {
      throw new TypeError("Failed to fetch");
    });
    expect(r.result).toEqual({ ok: false, message: FOLLOWUP_UNAVAILABLE });
    expect(r.saved).toBeNull();
  });

  it("a blank question is never sent", async () => {
    const store = await openRunStore(undefined);
    let calls = 0;
    const f = (async () => {
      calls++;
      return ndjson(lines({ type: "done" }));
    }) as unknown as typeof fetch;
    const r = await askFollowUp({ chatId: "live:r1", context, turns: [], question: "  \n " }, { fetch: f, store, onText: () => {}, now: () => "x" });
    expect(r).toEqual({ ok: false, message: "Type a question first." });
    expect(calls).toBe(0);
  });
});
