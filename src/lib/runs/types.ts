// Shapes a live run has in the browser. Client-safe: types only, so nothing here pulls server code (config, fs)
// or the pipeline's internal stage names into the bundle.
import type { RunEvent } from "../pipeline/events";
import type { CompanyProfile } from "../types";

/** What the browser POSTs to /api/run, and what Retry re-posts unchanged. */
export type RunRequest =
  | { profileId: string; windowStart: string; windowEnd: string }
  | { customProfile: CompanyProfile; windowStart: string; windowEnd: string };

export type RunDone = Extract<RunEvent, { type: "run.done" }>;

/**
 * running: the stream is open in this tab. interrupted: it ended without run.done or run.failed (dropped connection,
 * server timeout, refused request, or the page reloaded mid-run), so the run can only be retried, never resumed.
 */
export type RunStatus = "running" | "done" | "failed" | "interrupted";

/**
 * One run as saved in IndexedDB. Holds only what the browser was sent: never the server's RunConfig or the
 * pipeline's decisions, which carry model ids and internal scores.
 */
export interface StoredRun {
  id: string;
  createdAt: string;
  request: RunRequest;
  events: RunEvent[];
  status: RunStatus;
  /** The run.done event, once it arrives. */
  result: RunDone | null;
  /** The profile the run used, as it was when the run started (a preset or the GC's own). */
  profile: CompanyProfile;
  /**
   * Document numbers of held-back items the GC added after checking them ("Add after checking"), in the order added.
   * Applied after reduceEvents (applyConfirmed); `events` stay what the server sent. Absent on runs saved before
   * confirmations existed, which read as none confirmed.
   */
  confirmed?: string[];
}

/**
 * A profile the GC edited or wrote, saved in this browser when a run used it, and offered again under "Company
 * profiles". Keyed by `key`, not `profile.id`: an edited preset keeps the preset's id, and several edits of one
 * preset can sit side by side.
 */
export interface SavedProfile {
  key: string;
  /** ISO timestamp of the last save; the picker lists newest first. */
  savedAt: string;
  profile: CompanyProfile;
}

/**
 * One row of public/examples/index.json: a recorded example run the GC sidebar lists under "Examples". Generated by
 * scripts/build-examples.mts (src/lib/pipeline/recorded.ts); the browser reads only these public files.
 */
export interface ExampleSummary {
  id: string;
  company: string;
  windowStart: string;
  windowEnd: string;
  /** How many items the report has. */
  items: number;
}

/** public/examples/<id>.json: the example's public events (rendered through reduceEvents) and the profile it ran with. */
export interface ExampleRun extends ExampleSummary {
  profile: CompanyProfile;
  events: RunEvent[];
}

/** One message of a follow-up conversation about a finished report. */
export interface ChatTurn {
  role: "user" | "assistant";
  content: string;
}

/**
 * A follow-up conversation, saved in its own IndexedDB store (never on the run record: an example has no run record).
 * Keyed `live:<runId>` or `example:<exampleId>`. Holds only finished question-and-answer pairs.
 */
export interface StoredChat {
  id: string;
  /** ISO timestamp of the last save. */
  savedAt: string;
  turns: ChatTurn[];
}
