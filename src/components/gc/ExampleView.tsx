"use client";

import { Info } from "lucide-react";
import { useEffect, useMemo, useState } from "react";
import { AppShell } from "@/components/shell/AppShell";
import { loadExample } from "@/lib/runs/examples";
import { buildFollowUpContext, followUpChatId } from "@/lib/runs/followup-context";
import { reduceEvents, type RunViewState } from "@/lib/runs/reduce";
import { formatWindow, sortItems } from "@/lib/runs/report";
import type { ExampleRun } from "@/lib/runs/types";
import type { ActionItem } from "@/lib/types";
import { FollowUpChat } from "./FollowUpChat";
import { GcSidebar, type SidebarUser } from "./GcSidebar";
import { ReportView } from "./ReportView";
import { RunSteps } from "./RunSteps";
import { SourcesPanel } from "./SourcesPanel";

/**
 * A recorded example run, rendered with the same Report screen as a live run: its public events (/examples/<id>.json,
 * generated by scripts/build-examples.mts) through reduceEvents. Read-only: no Retry, and held-back items can be
 * opened on the Federal Register but not added. The follow-up chat is the one thing an example writes to IndexedDB
 * (its turns, under `example:<id>`); `suggestions` are its chips (config/app.yaml → followUp).
 */
export function ExampleView({ id, appName, user, suggestions }: { id: string; appName: string; user: SidebarUser | null; suggestions: string[] }) {
  const [state, setState] = useState<{ example: ExampleRun | null; error: string | null }>({ example: null, error: null });
  useEffect(() => {
    let live = true;
    loadExample(id)
      .then((example) => live && setState({ example, error: null }))
      .catch((e: Error) => live && setState({ example: null, error: e.message }));
    return () => {
      live = false;
    };
  }, [id]);
  const ex = state.example;
  const view = useMemo(() => (ex ? reduceEvents(ex.events) : null), [ex]);
  const items = useMemo(() => (view ? sortItems(view.items) : []), [view]);

  return (
    <AppShell
      sidebar={<GcSidebar appName={appName} user={user} activeRunId={id} />}
      asideLabel="Sources and profile"
      aside={ex && view ? <SourcesPanel items={items} profile={ex.profile} /> : undefined}
    >
      {ex ? (
        <div className="flex flex-wrap items-center gap-2.5 border-b border-border-subtle px-5 py-3">
          <span className="grow font-medium">
            {ex.company.split(/\s+/)[0]} · {formatWindow(ex.windowStart, ex.windowEnd)}
          </span>
          <span className="rounded-full bg-status-neutral-surface px-2.5 py-[3px] text-[13px] text-status-neutral-fg">Example run</span>
        </div>
      ) : null}
      <div className="px-5 py-6 sm:px-8">
        <div className="mx-auto flex max-w-[800px] flex-col gap-[22px]">
          {!ex && !state.error ? <p className="m-0 text-muted-foreground">Loading example…</p> : null}
          {state.error ? (
            <div className="flex flex-col items-start gap-2">
              <h1 className="m-0 text-2xl font-bold text-heading">Example not found</h1>
              <p className="m-0 text-muted-foreground">There is no recorded example with this link.</p>
            </div>
          ) : null}
          {ex && view ? <ExampleReport example={ex} view={view} items={items} suggestions={suggestions} /> : null}
        </div>
      </div>
    </AppShell>
  );
}

/** A loaded example's Report, with the follow-up chat under it when the recorded run finished. */
export function ExampleReport({ example, view, items, suggestions }: { example: ExampleRun; view: RunViewState; items: ActionItem[]; suggestions: string[] }) {
  const chatId = followUpChatId("example", example.id, view.status);
  const context = useMemo(() => (chatId ? buildFollowUpContext(view, example.profile) : null), [chatId, view, example.profile]);
  return (
    <>
      <p className="m-0 inline-flex items-center gap-2 self-start rounded-lg bg-secondary px-3 py-1.5 text-[13px]">
        <Info aria-hidden="true" className="size-3.5 shrink-0" />A recorded run, shown as it finished. Start a new run to triage this week yourself.
      </p>
      <ReportView
        view={view}
        items={items}
        company={view.company ?? example.company}
        trace={<RunSteps steps={view.steps} live={false} />}
        followUp={chatId && context ? <FollowUpChat chatId={chatId} context={context} suggestions={suggestions} /> : undefined}
      />
    </>
  );
}
